// ff_meta.h - IL2CPP metadata as it sits in the running process.
//
// Every number in Layout below was measured from Free Fire 1.132.1 and is what
// tools/ffdump/ffdump.py proved, then re-used here unchanged:
//
//   type table    stride 88, 43,627 entries
//   field table   stride 12, 475,641 entries
//   method table  stride 40, 336,329 entries
//   inside a type, field count is uint16 at +68 and method count at +64
//   field start is int32 at +32, method start at +36
//
// The field *offsets* are not in the metadata. They are in libil2cpp.so, in the
// array reached from Il2CppMetadataRegistration, and that is what this reads.
#pragma once

#include <cstdint>
#include <string>
#include <vector>

#include "ff_mem.h"

namespace ff {

// IL2CPP's own sanity value, followed by the metadata version.
constexpr uint32_t kMetadataSanity = 0xFAB11BAF;
constexpr int32_t kMetadataVersion = 31;

struct Layout {
    int32_t type_offset;
    int32_t type_stride;
    int32_t type_capacity;      // bytes reserved for the table in the file
    int32_t string_offset;
    int32_t string_length;
    int32_t field_offset;
    int32_t field_stride;
    int32_t method_offset;
    int32_t method_stride;
    int32_t type_field_start;
    int32_t type_method_start;
    int32_t type_method_count;
    int32_t type_field_count;
};

// Free Fire 1.132.1, metadata v31. Regenerated by tools/ffdump/ffdump.py.
constexpr Layout kLayoutFF132 = {
        51171844, 88, 3839176,
        2002364, 16048368,
        41969288, 12,
        18574128, 40,
        32, 36, 64, 68,
};

// RVAs inside libil2cpp.so. One arm64 binary serves every phone, so these are
// the same on all of them for a given game version.
constexpr uintptr_t kMetadataRegistrationRVA = 0xa5c7f60;
constexpr int32_t kMetadataRegistrationFieldOffsets = 0x58;

struct TypeInfo {
    int32_t index = -1;
    int32_t name_index = 0;      // offset into the metadata string blob
    std::string name;
    std::string namespaze;
    int32_t field_start = 0;
    int32_t field_count = 0;
    int32_t method_start = 0;
    int32_t method_count = 0;

    std::string full() const {
        return namespaze.empty() ? name : namespaze + "." + name;
    }
};

class Meta {
public:
    Meta(const Memory& mem, const Layout& layout, uintptr_t metadata_base,
         uintptr_t il2cpp_base, uintptr_t offsets_array_override = 0);

    uintptr_t base() const { return base_; }
    int32_t type_count() const { return type_count_; }

    // Where the metadata keeps the string for an index. IL2CPP points
    // Il2CppClass.name straight at these bytes, which is what makes the class
    // findable without any symbol: the address is a value to search for.
    uintptr_t string_address(int32_t index) const {
        return base_ + static_cast<uintptr_t>(
                static_cast<uint32_t>(layout_.string_offset + index));
    }

    bool type_info(int32_t index, TypeInfo& out) const;
    int32_t find_type(const std::string& name, const std::string& namespaze) const;
    int32_t find_type_any(const std::string& full_name) const;

    // The byte offset of a field inside its object, or -1.
    int32_t field_offset(const TypeInfo& type, int32_t field_index) const;
    bool field_name(const TypeInfo& type, int32_t field_index, std::string& out) const;
    int32_t field_index_by_name(const TypeInfo& type, const std::string& name) const;

    bool method_name(const TypeInfo& type, int32_t index, std::string& out) const;

    // True when the field-offset array was reachable, which is what makes
    // field_offset() meaningful rather than a guess.
    bool offsets_ready() const { return offsets_array_ != 0; }

    static uintptr_t find_metadata_base(const Memory& mem,
                                        uintptr_t& scan_begin, uintptr_t& scan_end);

private:
    std::string string_at(int32_t index) const;

    // A pointer from the image may already be absolute or may still be a
    // link-time virtual address.
    //
    // In a running process the linker has applied every relocation, so the
    // value read out of the binary is an address and can be used as is. In the
    // file it has not, so the value is an offset from the load base. Both are
    // handled because the same decoder reads both, and getting this wrong
    // produces a pointer that is not mapped - which looks like "the game
    // changed" rather than "the pointer was not relocated".
    uintptr_t resolve(uintptr_t value) const;

    const Memory& mem_;
    Layout layout_;
    uintptr_t base_;
    uintptr_t il2cpp_base_;
    int32_t type_count_;
    uintptr_t offsets_array_;
};

}  // namespace ff
